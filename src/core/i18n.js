let locale = 'en';
export function setLocale(next) {
  locale = next === 'zh' ? 'zh' : 'en';
  document.documentElement.lang = locale === 'zh' ? 'zh-CN' : 'en';
  localStorage.setItem('climb-language', locale);
}
export function getLocale() { return locale; }
export function initLocale(saved) { setLocale(saved || localStorage.getItem('climb-language') || 'en'); }

export function t(value) {
  if (locale !== 'zh' || typeof value !== 'string') return value;
  if (ZH[value]) return ZH[value];
  const quote = value.match(/^“(.+)”$/);
  if (quote) return `“${t(quote[1])}”`;
  let s = value;
  const replacements = [
    [/^Enter: (.+)$/, (_, x) => `进入：${t(x)}`],
    [/^Rest \(\+(\d+) HP\)$/, (_, n) => `休息（恢复 ${n} 点生命）`],
    [/^Remove a card \((\d+)g\)$/, (_, n) => `移除一张牌（${n} 金币）`],
    [/^Remove one card for (\d+) gold\.$/, (_, n) => `花费 ${n} 金币移除一张牌。`],
    [/^HP (\d+\/\d+)$/, '生命 $1'], [/^GOLD (\d+)$/, '金币 $1'], [/^FLOOR (\d+)$/, '层数 $1'],
    [/^Deck: (\d+) cards$/, '牌组：$1 张'], [/^Relics: (.+)$/, (_, x) => `遗物：${x.split(' · ').map(t).join(' · ')}`],
    [/^DRAW (\d+)$/, '抽牌堆 $1'], [/^DISC (\d+)$/, '弃牌堆 $1'], [/^Phase: (.+)$/, '阶段：$1'],
    [/^W\/L (\d+)\/(\d+)$/, '胜/负 $1/$2'], [/^(.+) · HP (\d+)$/, (_, x, n) => `${t(x)} · 生命 ${n}`],
    [/^— Turn (\d+) —$/, '— 第 $1 回合 —'], [/^Play (.+)$/, (_, x) => `打出 ${t(x)}`],
    [/^Relic: (.+)$/, (_, x) => `遗物触发：${t(x)}`], [/^Energy \+(\d+)$/, '能量 +$1'], [/^Next turn energy \+(\d+)$/, '下回合能量 +$1'],
    [/^(.+) hits (.+) for (\d+) \((\d+) HP\)$/, (_, a, b, n, hp) => `${t(a)} 对 ${t(b)} 造成 ${n} 点伤害（损失 ${hp} 生命）`],
    [/^(.+) hits (.+) for (\d+) \(blocked\)$/, (_, a, b, n) => `${t(a)} 攻击 ${t(b)}，${n} 点伤害被格挡`],
    [/^(.+) is down\.$/, (_, x) => `${t(x)} 已倒下。`], [/^(.+) gains (\d+) Block$/, (_, x, n) => `${t(x)} 获得 ${n} 点格挡`],
    [/^(.+) heals (\d+)$/, (_, x, n) => `${t(x)} 恢复 ${n} 点生命`], [/^(.+) loses (\d+) HP(?: \((.+)\))?$/, (_, x, n, why) => `${t(x)} 损失 ${n} 点生命${why ? `（${t(why)}）` : ''}`],
    [/^(.+) gains (.+) (\d+)$/, (_, x, status, n) => `${t(x)} 获得 ${t(status)} ${n} 层`],
    [/^(.+) intent reduced by (\d+)$/, (_, x, n) => `${t(x)} 的意图伤害降低 ${n}`], [/^([^:]+): (.+)$/, (_, x, y) => `${t(x)}：${t(y)}`],
    [/^Yo, Science! — free card$/, '科学的力量！本张牌消耗为 0'], [/^Setup consumed \(\+50% dmg\)$/, '准备状态消耗（伤害 +50%）'], [/^Critical! \(Heisenberg Hat\)$/, '暴击！（海森堡之帽）'],
    [/^Deal (.+) damage\.$/, '造成 $1 点伤害。'], [/^Gain (.+) Block\.$/, '获得 $1 点格挡。'],
    [/^Added card to deck\.$/, '卡牌已加入牌组。'], [/^Not enough energy\.$/, '能量不足。'], [/^Choose a target\.$/, '请选择目标。'],
  ];
  for (const [re, out] of replacements) if (re.test(s)) return s.replace(re, out);
  return s;
}
